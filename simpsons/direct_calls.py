#!/usr/bin/env python3
"""Lets the compiler inline calls between recompiled functions.

Generated code calls each guest function through its public name (sub_XXXXXXXX),
a weak alias of the implementation (__imp__sub_XXXXXXXX) so that handwritten
code can replace the function by defining that name. A weak alias can't be
inlined, so every guest call stays a real call, register spills and all.

For each generated translation unit this writes a header, force-included
before the unit, that makes calls to functions nothing else defines go straight
to their implementations (#define sub_X __imp__sub_X), where ThinLTO can inline
them. Functions whose names appear anywhere in handwritten sources keep the old
weak alias and call path, so hooks keep working. The aliases of the direct
functions are strong: if a hook ever defines one of them anyway, the link fails
with a duplicate symbol instead of the hook being silently skipped.

direct_calls.py --out DIR --scan DIR [--scan DIR ...] GENERATED.cpp ...
Headers are only rewritten when their contents change, so editing a
handwritten file rebuilds only the units whose calls it affects.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

NAME = r'(?:sub_[0-9A-F]{8}|__(?:save|rest)(?:gpr|fpr|vmx)(?:lr)?_\d+)'
TOKEN = re.compile(r'\b' + NAME + r'\b')
DEFINE = re.compile(r'^DEFINE_REX_FUNC\((\w+)\)', re.M)
CACHE_VERSION = 2
SCAN_SUFFIXES = {'.c', '.cc', '.cpp', '.cxx', '.h', '.hh', '.hpp', '.hxx', '.inl', '.inc', '.ipp',
                 '.m', '.mm'}


def write_if_changed(path, text):
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(text)
    os.replace(tmp, path)
    return True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', required=True)
    parser.add_argument('--scan', action='append', default=[])
    parser.add_argument('--stamp')
    parser.add_argument('units', nargs='+')
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # What each generated unit defines and names, cached by file size and time:
    # the units are large and rarely change.
    cache_path = out / 'units.json'
    try:
        cache = json.loads(cache_path.read_text())
    except (OSError, ValueError):
        cache = {}
    # Parsed by another version of this script: parse again.
    if cache.pop('version', None) != CACHE_VERSION:
        cache = {}
    units = []
    for unit in args.units:
        path = Path(unit).resolve()
        st = path.stat()
        key = str(path)
        entry = cache.get(key)
        if not entry or entry['size'] != st.st_size or entry['mtime'] != st.st_mtime_ns:
            text = path.read_text(errors='replace')
            entry = {'size': st.st_size, 'mtime': st.st_mtime_ns,
                     'defines': sorted(set(DEFINE.findall(text))),
                     'names': sorted(set(TOKEN.findall(text)))}
            cache[key] = entry
        units.append((path, entry))
    cache = {str(p): e for p, e in units}
    cache['version'] = CACHE_VERSION
    write_if_changed(cache_path, json.dumps(cache))

    # Anything handwritten that names a function may define it (a hook).
    generated_dirs = {p.parent for p, _ in units}
    named = set()
    for root in args.scan:
        for dirpath, dirnames, filenames in os.walk(root):
            if Path(dirpath).resolve() in generated_dirs:
                dirnames[:] = []
                continue
            for filename in filenames:
                if Path(filename).suffix.lower() in SCAN_SUFFIXES:
                    try:
                        text = (Path(dirpath) / filename).read_text(errors='replace')
                    except OSError:
                        continue
                    named.update(TOKEN.findall(text))

    defined = set()
    for _, entry in units:
        defined.update(entry['defines'])
    # Only the plainly named functions; the entry point and other named ones keep
    # their usual path.
    direct = {name for name in defined if TOKEN.fullmatch(name)} - named

    for path, entry in units:
        if not entry['defines']:
            continue
        lines = [
            '// Generated by direct_calls.py from the recompiled code and the handwritten',
            '// sources; do not edit.',
            '#pragma once',
            '#include "simpsons_init.h"',
            '',
            '// The implementation is defined by the unit; its public name is declared here,',
            '// before the names below become the implementations\'.',
            '#undef DEFINE_REX_FUNC',
            '#define DEFINE_REX_FUNC(name) REX_EXTERN(__imp__##name)',
        ]
        for name in entry['defines']:
            if name in direct:
                lines.append(f'extern "C" __attribute__((alias("__imp__{name}"))) REX_FUNC({name});')
            else:
                lines.append(f'extern "C" __attribute__((alias("__imp__{name}"))) '
                             f'REX_WEAK_FUNC({name});')
        lines.append('')
        for name in entry['names']:
            if name in direct:
                lines.append(f'#define {name} __imp__{name}')
        write_if_changed(out / (path.name[:-len(path.suffix)] + '.h'), '\n'.join(lines) + '\n')

    if args.stamp:
        Path(args.stamp).write_text(f'{len(direct)} of {len(defined)} functions called directly\n')
    print(f'direct_calls: {len(direct)} of {len(defined)} guest functions called directly')
    return 0


if __name__ == '__main__':
    sys.exit(main())
